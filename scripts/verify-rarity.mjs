import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../dist/index.html',import.meta.url),'utf8');
const source=html.slice(html.indexOf('const lvlOf='),html.indexOf('function openBooster(n)'));
const rarityData=vm.runInNewContext(html.match(/const rarityData=(\[[\s\S]*?\]);/)[1]);
const cards=rarityData.map(r=>({id:r.name,rarity:r.name}));
const random=Object.create(Math);
const sandbox={rarityData,LOCAL_CARDS:cards.slice(),BOOST:[{id:'mix'}],state:{selectedBooster:'mix'},stock:{pm:0,pl:0},PITY_M:250,PITY_L:50,BOOSTER_SLOT_MINS:JSON.parse(html.match(/const BOOSTER_SLOT_MINS=(\[[^;]+\]);/)[1]),rarityFor:c=>rarityData.find(r=>r.name===c.rarity),Math:random};
vm.createContext(sandbox);vm.runInContext(source,sandbox);
random.random=()=>.999999;
assert.deepEqual(Array.from(sandbox.sampleBooster(),c=>c.rarity),['Commun','Commun','Commun','Peu commune','Rare']);
sandbox.stock.pm=249;sandbox.stock.pl=49;
assert.equal(sandbox.boosterRarityOdds().Mythique,1);
assert.equal(sandbox.sampleBooster().at(-1).rarity,'Mythique');
assert.deepEqual(sandbox.stock,{pm:0,pl:0});
sandbox.stock.pl=49;
assert.equal(sandbox.sampleBooster().at(-1).rarity,'Légendaire');
assert.equal(sandbox.stock.pl,0);
sandbox.LOCAL_CARDS.splice(0,sandbox.LOCAL_CARDS.length,...cards.filter(c=>sandbox.rarityFor(c).level>=3));
sandbox.stock.pm=0;sandbox.stock.pl=0;
assert.ok(sandbox.sampleBooster().every(c=>c.rarity==='Rare'));
assert.deepEqual(sandbox.stock,{pm:1,pl:1});
sandbox.stock.pm=0;sandbox.stock.pl=0;
const predicted=sandbox.boosterRarityOdds(),observed=Object.fromEntries(rarityData.map(r=>[r.name,0]));
const currentWeights=rarityData.map(r=>r.weight);
rarityData.find(r=>r.level===5).weight=.7;
rarityData.find(r=>r.level===3).weight=12;
const previous=sandbox.boosterRarityOdds();
rarityData.forEach((r,i)=>r.weight=currentWeights[i]);
assert.ok(predicted['Légendaire']<previous['Légendaire']/3);
for(const name of ['Épique','Mythique'])assert.ok(Math.abs(predicted[name]-previous[name])<1e-12);
assert.ok(Math.abs(rarityData.reduce((sum,r)=>sum+r.weight,0)-100)<1e-12);
let seed=8675309;
random.random=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/2**32);
const trials=100000;
for(let i=0;i<trials;i++){sandbox.stock.pm=0;sandbox.stock.pl=0;for(const name of new Set(sandbox.sampleBooster().map(c=>c.rarity)))observed[name]++;}
for(const r of rarityData)assert.ok(Math.abs(observed[r.name]/trials-predicted[r.name])<.003,'Displayed odds disagree with actual draws for '+r.name);
assert.equal(sandbox.formatBoosterChance(99.99954),'>99,9 %');
assert.equal(sandbox.formatBoosterChance(100),'100,0 %');
console.log(JSON.stringify({slotMinimums:'passed',mythicGuarantee:'passed',legendaryGuarantee:'passed',missingTiers:'upgrade to nearest available',pityResets:'based on actual cards',legendaryReduction:'more than 3 times rarer outside guarantee',epicAndMythicOdds:'unchanged',simulation:trials,previousLegendaryPercent:previous['Légendaire']*100,predictedPercent:Object.fromEntries(Object.entries(predicted).map(([k,v])=>[k,Number((v*100).toFixed(5))])),observedPercent:Object.fromEntries(Object.entries(observed).map(([k,v])=>[k,v/trials*100]))},null,2));
